#!/usr/bin/env bash
# Verification of the family layer (ChiquipoliFamily/). Run from `lean/`
# (or `make lean-family`):
#
#     ./verify_family.sh
#
# The same five checks verify.sh runs on the A16 development, applied to the
# Bingane–Audet family certificates:
#
#   1. the library builds;
#   2. no source admits a goal (`sorry` / `sorryAx`), and no `native_decide`;
#   3. every audited theorem depends only on Lean's three standard axioms;
#   4. every case's negative controls do NOT compile, and each control's twin
#      -- the same proof of the true statement -- DOES;
#   5. every generated file (ChiquipoliFamily/Polynomial/A<n>/, the root module A<n>.lean,
#      the shared ChiquipoliFamily/Chebyshev.lean, negative_controls_family/A<n>/)
#      reproduces byte for byte from
#      lean/generators/family/gen_family.jl.
#
# FAMILY_STEPS="2 4" runs only the listed steps (default: all five),
# FAMILY_CASES="16" only the listed A cases and FAMILY_ZCASES="" none of the Z cases. They exist for tools/stress_family.sh,
# which checks that each step rejects the defect it is responsible for. A run
# restricted either way prints "partial run, not a certification".
#
# It is separate from verify.sh on purpose: the A16 development, its counts and
# the numbers the article quotes are untouched by anything here.

set -uo pipefail
cd "$(dirname "$0")"

CASES="${FAMILY_CASES:-16 32 64}"
# The Bingane-Audet polygons Z_n (no published constructor): Z32 generated by gen_z.jl,
# Z64 by gen_z64.jl. Each has a uniqueness theorem for its root (Unique.lean; for Z64 among the
# polygons that exist) and ten negative controls.
ZCASES="${FAMILY_ZCASES:-32 64}"
AXIOM_AUDIT_MIN=92
NEGATIVE_CONTROLS_PER_CASE=11
NEGATIVE_CONTROLS_PER_ZCASE=10
STEPS="${FAMILY_STEPS:-1 2 3 4 5}"
want() { case " $STEPS " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

RED=$'\033[31m'; GRN=$'\033[32m'; YEL=$'\033[33m'; RST=$'\033[0m'
fail=0
note() { printf '%s\n' "$*"; }
ok()   { printf "  ${GRN}PASS${RST}  %s\n" "$*"; }
bad()  { printf "  ${RED}FAIL${RST}  %s\n" "$*"; fail=1; }
skip() { printf "  ${YEL}SKIP${RST}  %s\n" "$*"; }

if want 1; then
note "=== 1. build ==="
if lake build ChiquipoliFamily >/tmp/chiqui_family_build.log 2>&1; then
  ok "lake build ChiquipoliFamily"
else
  bad "lake build ChiquipoliFamily (see /tmp/chiqui_family_build.log)"
  tail -20 /tmp/chiqui_family_build.log
  exit 1
fi
note ""
fi

if want 2; then
note "=== 2. no admitted goals ==="
# Same comment-stripping as verify.sh, so prose about `sorry` is not a hit.
strip_lean_comments() {
  awk '
    BEGIN { depth = 0 }
    {
      line = $0; out = ""; i = 1
      while (i <= length(line)) {
        two = substr(line, i, 2)
        if (depth == 0 && two == "--") break
        if (two == "/-") { depth++; i += 2; continue }
        if (two == "-/") { if (depth > 0) depth--; i += 2; continue }
        if (depth == 0) out = out substr(line, i, 1)
        i++
      }
      print FILENAME ":" FNR ":" out
    }' "$1"
}
hits=""; nsrc=0
while IFS= read -r f; do
  nsrc=$((nsrc + 1))
  h=$(strip_lean_comments "$f" | grep -E '\bsorry\b|sorryAx|native_decide|\badmit\b' || true)
  [ -n "$h" ] && hits="${hits}${h}"$'\n'
done < <(find ChiquipoliFamily.lean ChiquipoliFamily negative_controls_family -name '*.lean' | sort)
if [ -n "${hits//[$'\n' ]/}" ]; then
  bad "a source file admits a goal"
  printf '%s' "$hits"
else
  ok "no 'sorry', 'admit' or 'native_decide' in any of the $nsrc source, control and twin files (comments excluded)"
fi
note ""
fi

if want 3; then
note "=== 3. axiom audit ==="
axout=$(lake env lean ChiquipoliFamily/Audit.lean 2>&1)
axrc=$?
if [ "$axrc" -ne 0 ] || printf '%s' "$axout" | grep -qi 'error'; then
  bad "ChiquipoliFamily/Audit.lean does not compile — the axiom audit is not being performed"
  printf '%s\n' "$axout" | grep -i 'error' | head -5
else
  n=$(printf '%s\n' "$axout" | grep 'depends on axioms' \
      | sed "s/^'\([^']*\)'.*/\1/" | sort -u | wc -l | tr -d ' ')
  bad_lines=$(printf '%s\n' "$axout" | grep 'depends on axioms' \
      | grep -v '\[propext, Classical.choice, Quot.sound\]' || true)
  missing=""
  for c in $CASES; do
    for t in locally_maximal locally_maximal_unique published_locally_maximal Q_eq_P F_eq Ieq_imp_R stationary; do
      printf '%s\n' "$axout" | grep -qF "'Chiquipoli.Family.A$c.$t' depends on axioms" \
        || missing="$missing A$c.$t"
    done
  done
  for c in $ZCASES; do
    rootthm=Fc_root; [ "$c" = 64 ] && rootthm=G_root     # Z64 has no polynomial Fc: its root equation is G
    zextra=locally_maximal_unique     # the root is unique in (0, pi/n] (Z64: among the polygons that exist)
    for t in locally_maximal locally_maximal_at Ieq_imp_R stationary lam_pos $rootthm $zextra; do
      printf '%s\n' "$axout" | grep -qF "'Chiquipoli.Family.Z$c.$t' depends on axioms" \
        || missing="$missing Z$c.$t"
    done
  done
  # Each condition is reported on its own: a dropped headline theorem also
  # lowers the count, and reporting only the count would hide which one went.
  [ -n "$bad_lines" ] && { bad "unexpected axioms:"; printf '%s\n' "$bad_lines"; }
  [ "$n" -lt "$AXIOM_AUDIT_MIN" ] && bad "only $n theorems audited, expected at least $AXIOM_AUDIT_MIN"
  [ -n "$missing" ] && bad "headline theorems missing from the audit:$missing"
  if [ -z "$bad_lines" ] && [ "$n" -ge "$AXIOM_AUDIT_MIN" ] && [ -z "$missing" ]; then
    ok "$n theorems depend only on [propext, Classical.choice, Quot.sound]"
    ok "every case's headline theorems are audited by name (A: $CASES; Z: $ZCASES)"
  fi
fi
note ""
fi

if want 4; then
note "=== 4. negative controls: each must FAIL, its twin must COMPILE ==="
# Every case has the same NEGATIVE_CONTROLS_PER_CASE controls, generated with
# the certificate. A control is a false statement attempted with the
# certificate's own proof; its twin (twin/<same name>) is that proof of the true
# statement. A rejection counts only if the twin compiles -- otherwise the
# control might fail for a reason unrelated to its claim -- and only if Lean
# actually refuted the proof: a name that did not resolve, a timeout or a
# recursion limit is not a refutation.
wrong_reason='unknown module|unknown package|could not resolve import|object file .* does not exist|no such file|unknown (identifier|constant|namespace)|deterministic\) timeout|maximum recursion depth'
stray=$(find negative_controls_family -maxdepth 1 -name '*.lean' | head -5)
[ -z "$stray" ] || bad "controls outside a case directory (not generated, not paired with a twin): $stray"
for lab in $(for c in $CASES; do echo A$c; done) $(for c in $ZCASES; do echo Z$c; done); do
  c="${lab#?}"; kind="${lab%$c}"
  d="negative_controls_family/$lab"
  nc_seen=0; nc_ok=0
  per=$NEGATIVE_CONTROLS_PER_CASE; [ "$kind" = Z ] && per=$NEGATIVE_CONTROLS_PER_ZCASE
  for f in "$d"/*.lean; do
    [ -e "$f" ] || continue
    nc_seen=$((nc_seen + 1)); b=$(basename "$f"); t="$d/twin/$b"
    if [ ! -f "$t" ]; then bad "$lab $b has no twin"; continue; fi
    if ncout=$(lake env lean "$f" 2>&1); then
      bad "$lab $b COMPILED -- the certificate proves a false statement, or the control is not false"
      continue
    elif printf '%s' "$ncout" | grep -qiE "$wrong_reason"; then
      bad "$lab $b rejected for the wrong reason:"; printf '%s\n' "$ncout" | grep -iE "$wrong_reason" | head -2
      continue
    fi
    if tout=$(lake env lean "$t" 2>&1); then
      if printf '%s' "$tout" | grep -qi 'sorry'; then
        bad "$lab $b: its twin compiles only by admitting a goal"
      else
        nc_ok=$((nc_ok + 1))
      fi
    else
      bad "$lab $b: its twin does NOT compile, so the rejection proves nothing"
      printf '%s\n' "$tout" | grep -m2 error
    fi
  done
  ntw=$(find "$d/twin" -name '*.lean' 2>/dev/null | wc -l | tr -d ' ')
  if [ "$nc_seen" -ne "$per" ] || [ "$ntw" -ne "$per" ]; then
    bad "$lab: found $nc_seen controls and $ntw twins, expected $per of each"
  elif [ "$nc_ok" -eq "$nc_seen" ]; then
    ok "$lab: all $nc_seen controls rejected by Lean, all $ntw twins compile"
  fi
done
note ""
fi

if want 5; then
note "=== 5. generated files match the Julia source of truth ==="
# The generator writes into a scratch directory (CHIQUI_OUTDIR), never over the
# tracked files, and the two trees must agree byte for byte: every certificate
# file, the root module of the case, and every control and twin.
if command -v julia >/dev/null 2>&1; then
  for lab in $(for c in $CASES; do echo A$c; done) $(for c in $ZCASES; do echo Z$c; done); do
    c="${lab#?}"; kind="${lab%$c}"
    gen=gen_family.jl; [ "$kind" = Z ] && gen=gen_z.jl; [ "$lab" = Z64 ] && gen=gen_z64.jl
    scratch=$(mktemp -d "${TMPDIR:-/tmp}/chiqui_family_$lab.XXXXXX")
    if (cd .. && CHIQUI_OUTDIR="$scratch" julia --project=. lean/generators/family/$gen "$c" >"$scratch.log" 2>&1); then
      d=$( { diff -rq "$scratch/ChiquipoliFamily/Polynomial/$lab" "ChiquipoliFamily/Polynomial/$lab";
             diff -q "$scratch/ChiquipoliFamily/Polynomial/$lab.lean" "ChiquipoliFamily/Polynomial/$lab.lean";
             [ "$kind" = A ] && diff -q "$scratch/ChiquipoliFamily/Chebyshev.lean" "ChiquipoliFamily/Chebyshev.lean";
             diff -rq "$scratch/negative_controls_family/$lab" "negative_controls_family/$lab"; } 2>&1 || true)
      if [ -z "$d" ]; then
        ok "$lab: $(ls ChiquipoliFamily/Polynomial/$lab/*.lean | wc -l | tr -d ' ') certificate files, the root module and $(find negative_controls_family/$lab -name '*.lean' | wc -l | tr -d ' ') control/twin files reproduce byte for byte"
      else
        bad "$lab: tracked files differ from a fresh run of the generator"; printf '%s\n' "$d" | head -10
      fi
    else
      bad "$lab: the generator failed (see $scratch.log)"; tail -5 "$scratch.log"
    fi
    rm -rf "$scratch"
  done
else
  skip "julia not on PATH -- cannot re-derive the generated files"
fi
note ""
fi

# A partial run is not a certification, and does not say so.
what="FAMILY LEAN CERTIFICATE"
[ "$STEPS" = "1 2 3 4 5" ] && [ "$CASES" = "16 32 64" ] && [ "$ZCASES" = "32 64" ] || what="FAMILY LEAN STEPS [$STEPS], CASES [$CASES] (partial run, not a certification)"
if [ "$fail" -eq 0 ]; then
  printf "${GRN}%s PASS${RST}\n" "$what"
else
  printf "${RED}%s FAIL${RST}\n" "$what"
fi
exit "$fail"
