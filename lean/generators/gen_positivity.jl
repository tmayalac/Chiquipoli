Fc  = AC.Fc_poly()
dFc = QQ[QQ(k) * Fc[k+1] for k in 1:length(Fc)-1]

lean_rat(q::QQ) = denominator(q) == 1 ? string(numerator(q)) :
    (numerator(q) < 0 ? "(-$(abs(numerator(q)))/$(denominator(q)))" :
                        "($(numerator(q))/$(denominator(q)))")

function horner(p::Vector{QQ}, var="c")
    n = length(p) - 1
    n == 0 && return lean_rat(p[1])
    e = lean_rat(p[n+1])
    for k in (n-1):-1:0
        e = p[k+1] == 0 ? "($e) * $var" : "($e) * $var + $(lean_rat(p[k+1]))"
    end
    return e
end

"""
Build the `HasDerivAt` chain matching the Horner form emitted for `p`.

Horner is `a_n` then repeatedly `* c` and `+ a_k`; `const_mul` performs the
first multiplication, so the chain alternates `.mul`/`.add_const` from there.
Zero coefficients emit no `.add_const`, exactly as the Horner printer omits
them.
"""
function deriv_chain(p::Vector{QQ})
    n = length(p) - 1
    id = "(hasDerivAt_id' (x := c))"
    ch = "($id.const_mul ($(lean_rat(p[n+1])) : ℝ))"
    if p[n] != 0
        ch = "($ch.add_const ($(lean_rat(p[n]))))"
    end
    for k in (n-2):-1:0
        ch = "($ch.mul $id)"
        if p[k+1] != 0
            ch = "($ch.add_const ($(lean_rat(p[k+1]))))"
        end
    end
    return ch
end

