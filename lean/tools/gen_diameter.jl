# Generate lean/ChiquipoliLean/Diameter.lean.
#
#     julia --project=. lean/tools/gen_diameter.jl
#
# Lifts the polynomial certificates of InactiveMargin.lean back to the
# trigonometric constructor and assembles the headline geometric fact:
#
#     the diameter of the A16 configuration is EXACTLY 1
#
# i.e. no pair of vertices is farther than 1 (all 120 pairs), and the fifteen
# declared active pairs attain it. The `∀ i j : Fin 16` form matters: it is
# what rules out "you forgot to check a pair", which a hand-written list of
# conjuncts could not.

include(joinpath(@__DIR__, "..", "..", "scripts", "_bootstrap.jl"))

const AC = A16Certificate
const OUT = joinpath(@__DIR__, "..", "ChiquipoliLean", "Diameter.lean")

sides = Tuple{Int,Int}[(i, mod(i + 1, 16)) for i in 0:15]
sides_norm = Set{Tuple{Int,Int}}((min(i, j), max(i, j)) for (i, j) in sides)
active = [(min(i, j), max(i, j)) for (i, j) in AC.ACTIVE_EDGES]
active_set = Set(active)
inactive = Tuple{Int,Int}[]
for i in 0:15, j in (i+1):15
    (i, j) in sides_norm || (i, j) in active_set || push!(inactive, (i, j))
end
@assert length(sides_norm) + length(active) + length(inactive) == 120

# The two sides whose identity consumes the constructor equation.
const COND = Set([(3, 4), (12, 13)])

blocks = String[]

# --- inactive pairs: strictly shorter than 1 --------------------------------
for (i, j) in inactive
    push!(blocks, """
theorem lt_one_$(i)_$(j) (z : ℝ) (hc : Real.cos z ∈ Set.Ioo clo chi) :
    sqd (p$i z) (p$j z) < 1 := by
  rw [red$i, red$j, sqd_reduce]
  have h := inactive_$(i)_$(j) (Real.cos z) (le_of_lt hc.1) (le_of_lt hc.2)
  linarith
""")
end

# --- sides: length^2 = 2 - 2cos z, and cos z > 1/2 on the bracket -----------
for (i, j) in sides
    a, b = min(i, j), max(i, j)
    cond = (a, b) in COND
    hyp = cond ? "(hF : Ffun z = 0) " : ""
    arg = cond ? " hF" : ""
    push!(blocks, """
theorem side_lt_one_$(i)_$(j) (z : ℝ) $(hyp)(hc : Real.cos z ∈ Set.Ioo clo chi) :
    sqd (p$i z) (p$j z) < 1 := by
  rw [side_$(i)_$(j) z$arg]
  have h := hc.1
  unfold clo at h
  linarith
""")
end

# --- the ∀-quantified diameter bound ---------------------------------------
haves = String[]
for (i, j) in inactive
    push!(haves, "  have h_$(i)_$(j) : sqd (p$i z) (p$j z) ≤ 1 := le_of_lt (lt_one_$(i)_$(j) z hc)")
end
for (i, j) in sides
    a, b = min(i, j), max(i, j)
    arg = (a, b) in COND ? " hF" : ""
    push!(haves, "  have s_$(i)_$(j) : sqd (p$i z) (p$j z) ≤ 1 := le_of_lt (side_lt_one_$(i)_$(j) z$arg hc)")
end
for (i, j) in active
    push!(haves, "  have a_$(i)_$(j) : sqd (p$i z) (p$j z) ≤ 1 := le_of_eq (diam_$(i)_$(j) z)")
end

# Every unordered pair maps to exactly one hypothesis, in a known vertex order.
# `assumption` over 120 facts in 256 cases costs ~30k unifications and blows the
# heartbeat budget, so instead emit the 256 proof terms explicitly: each goal
# gets one targeted `exact`, with no search at all.
lookup = Dict{Tuple{Int,Int},Tuple{String,Bool}}()   # (x,y) -> (name, needs_comm)
function register!(x, y, name)
    lookup[(x, y)] = (name, false)
    lookup[(y, x)] = (name, true)
end
for (i, j) in inactive; register!(i, j, "h_$(i)_$(j)"); end
for (i, j) in sides;    register!(i, j, "s_$(i)_$(j)"); end
for (i, j) in active;   register!(i, j, "a_$(i)_$(j)"); end
@assert length(lookup) == 240 "expected 240 ordered pairs, got $(length(lookup))"

bullets = String[]
for i in 0:15, j in 0:15
    if i == j
        push!(bullets, "  · rw [sqd_self]; norm_num")
    else
        name, comm = lookup[(i, j)]
        push!(bullets, comm ? "  · rw [sqd_comm]; exact $name" : "  · exact $name")
    end
end

diam_thm = """
/-- **No two vertices are farther apart than 1.**

Stated for every pair `i j : Fin 16` — including `i = j` — so the bound cannot
miss a pair: `16 * 16 = 256` cases, of which 16 are the diagonal and the other
240 are the $(length(inactive)) inactive, $(length(sides)) side and $(length(active)) pairs in both orders. -/
theorem sqd_le_one (z : ℝ) (hF : Ffun z = 0) (hc : Real.cos z ∈ Set.Ioo clo chi)
    (i j : Fin 16) : sqd (P i z) (P j z) ≤ 1 := by
$(join(haves, "\n"))
  fin_cases i <;> fin_cases j
$(join(bullets, "\n"))

/-- **The diameter is exactly 1**: no pair exceeds 1, and the pair `(0,7)`
attains it. -/
theorem diameter_eq_one (z : ℝ) (hF : Ffun z = 0) (hc : Real.cos z ∈ Set.Ioo clo chi) :
    (∀ i j : Fin 16, sqd (P i z) (P j z) ≤ 1) ∧ sqd (P 0 z) (P 7 z) = 1 := by
  refine ⟨sqd_le_one z hF hc, ?_⟩
  simp only [P, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.head_cons,
    Matrix.cons_val_succ, Matrix.cons_val_fin_one, Fin.isValue]
  exact diam_0_7 z
"""

open(OUT, "w") do io
    print(io, """/-
AUTO-GENERATED by `lean/tools/gen_diameter.jl` — do not edit by hand.

**The diameter of the A16 configuration is exactly 1.**

`Identities.lean` gives the fifteen declared active diagonals length exactly 1;
`InactiveMargin.lean` gives Bernstein certificates that the other $(length(inactive))
diagonals stay strictly below 1. This file lifts those polynomial statements
back to the trigonometric constructor and closes the count: the bound is proved
for *every* pair `i j : Fin 16`, so there is no room for a forgotten pair.

Why this matters beyond Prop 6.2(4). Proving "these fifteen diagonals equal 1"
does not say the object is a *small* polygon — some other diagonal could be
longer. `sqd_le_one` below is what makes the Lean object recognisably the
paper's: an equilateral hexadecagon of diameter exactly 1.
-/
import ChiquipoliLean.InactiveMargin
import ChiquipoliLean.Identities

namespace Chiquipoli

/-- Squared distance is symmetric. -/
lemma sqd_comm (a b : ℝ × ℝ) : sqd a b = sqd b a := by
  simp only [sqd]; ring

@[simp] lemma sqd_self (a : ℝ × ℝ) : sqd a a = 0 := by
  simp only [sqd]; ring

/-- The sixteen vertices as one indexed family, so the diameter bound can be
stated for *all* pairs rather than an enumerated list. -/
noncomputable def P (i : Fin 16) (z : ℝ) : ℝ × ℝ :=
  ![p0 z, p1 z, p2 z, p3 z, p4 z, p5 z, p6 z, p7 z,
    p8 z, p9 z, p10 z, p11 z, p12 z, p13 z, p14 z, p15 z] i

$(join(blocks, "\n"))
$diam_thm
end Chiquipoli
""")
end
println("inactive=", length(inactive), " sides=", length(sides), " active=", length(active))
println("wrote ", OUT)
