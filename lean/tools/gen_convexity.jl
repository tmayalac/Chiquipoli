# **Strict convexity and the labelled cyclic order (Prop 6.2(3)).**
#
# The Julia gate (`support_determinants` in src/A16Certificate.jl) is stronger
# than "each corner turns the right way": for every directed edge (i, i+1) and
# every other vertex j it requires
#
#     (p_{i+1} - p_i) x (p_j - p_i)  >  0,
#
# i.e. every vertex lies strictly to the left of every edge. That is convex
# position *and* the correct labelled cyclic order in one statement — 16 * 14 =
# 224 determinants. This file certifies all of them.
#
# Because every vertex is `(sin z * XC(c), YC(c))`, each determinant factors as
# `sin z * D(c)` with `D` a rational polynomial: the `sin z` comes out cleanly
# and the sign question is again purely polynomial, so the same Bernstein
# machinery applies.

include(joinpath(@__DIR__, "..", "..", "scripts", "_bootstrap.jl"))
include(joinpath(@__DIR__, "bernstein.jl"))
using .Bernstein

const AC = A16Certificate
const QQ = Rational{BigInt}
const OUT = joinpath(@__DIR__, "..", "ChiquipoliLean", "Convexity.lean")

const A = QQ(613, 625)
const B = QQ(980801, 1000000)
const M = QQ(3, 100)          # worst determinant clears 0.0384

LIMIT = length(ARGS) >= 1 ? parse(Int, ARGS[1]) : typemax(Int)

"D(c) with det = sin z * D(c)."
function Dpoly(i, ip, j)
    dX = AC.psub(AC._XC[ip+1], AC._XC[i+1]); dY = AC.psub(AC._YC[ip+1], AC._YC[i+1])
    qX = AC.psub(AC._XC[j+1],  AC._XC[i+1]); qY = AC.psub(AC._YC[j+1],  AC._YC[i+1])
    return AC.psub(AC.pmul(dX, qY), AC.pmul(dY, qX))
end

triples = Tuple{Int,Int,Int}[]
for i in 0:15
    ip = mod(i + 1, 16)
    for j in 0:15
        (j == i || j == ip) && continue
        push!(triples, (i, ip, j))
    end
end
@assert length(triples) == 224
emit = triples[1:min(LIMIT, length(triples))]
println("support determinants: ", length(triples), "   emitting: ", length(emit))

function build(ts)
    bern = String[]; corol = String[]; worst = nothing
    for (i, ip, j) in ts
        D = QQ.(Dpoly(i, ip, j))
        γ = Bernstein.bern_coeffs(D, A, B)
        m = minimum(γ)
        @assert m > M "triple ($i,$ip,$j) margin $(Float64(m)) below the uniform bound"
        worst = worst === nothing ? m : min(worst, m)
        expr = "(XC$ip c - XC$i c) * (YC$j c - YC$i c) - (YC$ip c - YC$i c) * (XC$j c - XC$i c)"
        push!(bern, Bernstein.lean_lower_bound_lemma(
            "convD_$(i)_$(j)", expr, D, A, B;
            m = M, unfolds = " XC$i XC$ip XC$j YC$i YC$ip YC$j"))
        push!(corol, """
theorem cross_pos_$(i)_$(j) (z : ℝ) (hs : 0 < Real.sin z)
    (hc : Real.cos z ∈ Set.Ioo clo chi) : 0 < cross (p$i z) (p$ip z) (p$j z) := by
  rw [red$i, red$ip, red$j, cross_reduce]
  exact mul_pos hs (by linarith [convD_$(i)_$(j) (Real.cos z) (le_of_lt hc.1) (le_of_lt hc.2)])
""")
    end
    return bern, corol, worst
end

bern, corol, worst = build(emit)
println("worst Bernstein lower bound: ", Float64(worst))

# --- the ∀-quantified statement --------------------------------------------
haves = ["  have c_$(i)_$(j) : 0 < cross (p$i z) (p$ip z) (p$j z) := cross_pos_$(i)_$(j) z hs hc"
         for (i, ip, j) in triples]
bullets = String[]
for i in 0:15, j in 0:15
    ip = mod(i + 1, 16)
    if j == i
        push!(bullets, "  · exact absurd rfl h₁")
    elseif j == ip
        push!(bullets, "  · exact absurd rfl h₂")
    else
        push!(bullets, "  · exact c_$(i)_$(j)")
    end
end

