# Generate lean/ChiquipoliLean/InactiveMargin.lean.
#
#     julia --project=. lean/tools/gen_inactive.jl [limit]
#
# Proves that every diagonal NOT in the declared active set is strictly shorter
# than 1, everywhere the root can live. Together with the fifteen active
# equalities (Identities.lean) this is what upgrades "these fifteen diagonals
# equal 1" to "the diameter is exactly 1", and it is the property that pins the
# object down: it rules out the object being some other equilateral polygon.
#
# Each of the 89 certificates is a Bernstein bound on `1 - |p_i - p_j|^2`,
# stated through the same `XC`/`YC` polynomials that `sqd_reduce` produces, so
# it composes directly with the trigonometric layer.
#
# Optional `limit` argument emits only the first N pairs (used to measure
# compile cost before generating the whole file).

include(joinpath(@__DIR__, "..", "..", "scripts", "_bootstrap.jl"))
include(joinpath(@__DIR__, "bernstein.jl"))
using .Bernstein

const AC = A16Certificate
const QQ = Rational{BigInt}
const OUT = joinpath(@__DIR__, "..", "ChiquipoliLean", "InactiveMargin.lean")

# The bracket fixed in RootExists.lean.
const A = QQ(613, 625)
const B = QQ(980801, 1000000)
# Uniform margin: the worst inactive pair, (4,12), clears 0.0161.
const M = QQ(1, 100)

LIMIT = length(ARGS) >= 1 ? parse(Int, ARGS[1]) : typemax(Int)

sides = Set{Tuple{Int,Int}}()
for i in 0:15
    j = mod(i + 1, 16)
    push!(sides, (min(i, j), max(i, j)))
end
active = Set{Tuple{Int,Int}}((min(i, j), max(i, j)) for (i, j) in AC.ACTIVE_EDGES)
inactive = Tuple{Int,Int}[]
for i in 0:15, j in (i+1):15
    (i, j) in sides || (i, j) in active || push!(inactive, (i, j))
end
@assert length(inactive) == 89 "expected 89 inactive pairs, got $(length(inactive))"

emit = inactive[1:min(LIMIT, length(inactive))]
println("inactive pairs: ", length(inactive), "   emitting: ", length(emit))

function build_lemmas(pairs)
    out = String[]
    worst = nothing
    for (i, j) in pairs
        g = AC.psub(QQ[QQ(1)], AC.sqdist_poly(i, j))     # 1 - |p_i - p_j|^2
        γ = Bernstein.bern_coeffs(QQ.(g), A, B)
        m = minimum(γ)
        @assert m > M "pair ($i,$j) margin $(Float64(m)) below the uniform bound"
        worst = worst === nothing ? m : min(worst, m)
        expr = "1 - ((1 - c ^ 2) * (XC$j c - XC$i c) ^ 2 + (YC$j c - YC$i c) ^ 2)"
        push!(out, Bernstein.lean_lower_bound_lemma(
            "inactive_$(i)_$(j)", expr, QQ.(g), A, B;
            m = M, unfolds = " XC$i XC$j YC$i YC$j"))
    end
    return out, worst
end

lemmas, worst = build_lemmas(emit)
println("worst Bernstein lower bound among emitted: ", Float64(worst))

open(OUT, "w") do io
    print(io, """/-
AUTO-GENERATED by `lean/tools/gen_inactive.jl` — do not edit by hand.

**The inactive margin (Prop 6.2(4)), verified by the Lean kernel.**

`Identities.lean` proves the fifteen declared active diagonals have length
exactly 1. On its own that does not say the diameter *is* 1 — some other
diagonal could be longer, and then the object would not be a small polygon at
all. This file closes that gap: each of the $(length(inactive)) remaining
diagonals is certified strictly shorter than 1, uniformly over the bracket in
which the constructor root lives.

Method: a Bernstein positivity certificate for `1 - |p_i - p_j|^2` on
`[clo, chi]`, exactly as in `Positivity.lean` — one `ring` identity plus
nonnegativity of each term. Exact rational arithmetic throughout; no interval
arithmetic and no floating point.

The tightest pair is `(4,12)`, clearing `0.0161`; every certificate below uses
the uniform margin `1/100`. That the binding pair is `(4,12)` agrees with the
Julia certificate, which reports the same critical pair.
-/
import ChiquipoliLean.Positivity

namespace Chiquipoli

$(join(lemmas, "\n"))
end Chiquipoli
""")
end
println("wrote ", OUT)
