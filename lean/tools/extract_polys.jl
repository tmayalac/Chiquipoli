# Emit the exact Q[c] layer of the A16 certificate as Lean definitions.
#
#     julia --project=. lean/tools/extract_polys.jl
#
# Only *definitions* are generated here — never proofs. The Lean development
# writes the trigonometric constructor independently, by hand, mirroring
# `coordinates(z)` in src/A16Certificate.jl; Lean then *proves* that the
# hand-written trigonometric form and this generated polynomial form agree
# (`ChiquipoliLean/Reduction.lean`). A transcription error on either side is
# therefore a compile error, not a silent wrong answer.

include(joinpath(@__DIR__, "..", "..", "scripts", "_bootstrap.jl"))

const AC = A16Certificate
const OUT = joinpath(@__DIR__, "..", "ChiquipoliLean", "Generated.lean")

lean_int(n::BigInt) = n < 0 ? "(-$(abs(n)))" : "$n"

function lean_rat(q::Rational{BigInt})
    denominator(q) == 1 && return lean_int(numerator(q))
    n = numerator(q); d = denominator(q)
    n < 0 ? "(-$(abs(n))/$d)" : "($n/$d)"
end

"Horner-form Lean expression for an RPoly in the variable `c`."
function lean_poly(p::AC.RPoly, var::String="c")
    p = AC.ptrim(p)
    AC.iszeropoly(p) && return "0"
    deg = length(p) - 1
    deg == 0 && return lean_rat(p[1])
    expr = lean_rat(p[deg+1])
    for k in (deg-1):-1:0
        coeff = p[k+1]
        expr = coeff == 0 ? "($expr) * $var" : "($expr) * $var + $(lean_rat(coeff))"
    end
    return expr
end

Fc = AC.Fc_poly()
XC, YC = AC._XC, AC._YC

# Re-verify, at generation time, the two facts the Lean file will encode:
# 29 identities are the identically-zero polynomial, and the remaining two have
# quotient exactly 1.
n_uncond = 0; n_cond = 0
for i in 0:15
    j = mod(i + 1, 16)
    R = AC.psub(AC.sqdist_poly(i, j), AC.side_target_poly())
    if AC.iszeropoly(R)
        global n_uncond += 1
    else
        q, r = AC.pdivrem(R, Fc)
        @assert AC.iszeropoly(r) "side ($i,$j) has nonzero remainder"
        @assert q == AC.RPoly([1//1]) "side ($i,$j) quotient is $q, expected [1]"
        global n_cond += 1
    end
end
for (i, j) in AC.ACTIVE_EDGES
    R = AC.psub(AC.sqdist_poly(i, j), AC.diameter_target_poly())
    @assert AC.iszeropoly(R) "diam ($i,$j) is not identically zero"
    global n_uncond += 1
end
@assert n_uncond == 29 && n_cond == 2
println("verified: $n_uncond unconditional, $n_cond conditional (quotient ≡ 1)")
println("deg Fc = ", length(Fc) - 1)

open(OUT, "w") do io
    println(io, """/-
AUTO-GENERATED by `lean/tools/extract_polys.jl` — do not edit by hand.

The polynomial layer of the A16 certificate, in `c = cos z`. Every coordinate
of the Bingane–Audet constructor has the exact form

    p i = (sin z * XC i (cos z),  YC i (cos z))

because each multiple angle reduces by the Chebyshev identities
`sin (k*z) = sin z * U (k-1) (cos z)` and `cos (k*z) = T k (cos z)`.
These coefficients come from the exact `Rational{BigInt}` arithmetic in
`src/A16Certificate.jl`; `ChiquipoliLean/Reduction.lean` proves that they
agree with the independently hand-written trigonometric constructor.
-/
import Mathlib.Data.Real.Basic

-- Several of these polynomials are constants (vertex 0 sits at the origin,
-- vertex 8 at the north pole), so their argument is genuinely unused.
set_option linter.unusedVariables false

namespace Chiquipoli
""")

    for i in 0:15
        println(io, "/-- `x`-polynomial of vertex $i: `p $i` has `x = sin z * XC$i (cos z)`. -/")
        println(io, "noncomputable def XC$i (c : ℝ) : ℝ := ", lean_poly(XC[i+1]))
        println(io)
    end
    for i in 0:15
        println(io, "/-- `y`-polynomial of vertex $i: `p $i` has `y = YC$i (cos z)`. -/")
        println(io, "noncomputable def YC$i (c : ℝ) : ℝ := ", lean_poly(YC[i+1]))
        println(io)
    end

    println(io, """/-- The constructor's defining polynomial: `Fc (cos z) = F z` for every real
`z`, where `F` is the scalar equation whose root fixes the A16 candidate. -/
noncomputable def Fc (c : ℝ) : ℝ := $(lean_poly(Fc))

end Chiquipoli""")
end

println("wrote ", OUT)
