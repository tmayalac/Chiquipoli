# Literature validation driver.
#
# Scans cases/**/candidate.jl, runs the general SmallPolygons
# certifier on each, prints an honest summary with four strictly-separate
# epistemic levels, and — on every run — writes a reproducible certificate and
# LaTeX tables under results/.
#
#   PROVEN      — established here by exact arithmetic.
#   CERTIFIED   — established here rigorously by interval arithmetic.
#   NUMERICAL   — high-precision floating diagnostic, NOT a certificate.
#   (literature) THEOREM / OPEN — status of the RESULT in the literature, which
#               this framework never re-proves.
#
# Negative controls (`:expect => :reject`) must be REJECTED (some block :FAIL).

const ROOT = normpath(joinpath(@__DIR__, ".."))
include(joinpath(ROOT, "src", "A16Certificate.jl"));  using .A16Certificate
include(joinpath(ROOT, "src", "ExactIdentity.jl"));   using .ExactIdentity
include(joinpath(ROOT, "src", "SmallPolygons.jl"));   using .SmallPolygons
include(joinpath(ROOT, "cases", "exact_coords.jl"))
using IntervalArithmetic, Dates, Printf, SHA, TOML

setprecision(BigFloat, 256)

const BLOCK_ORDER = ["existence", "equilaterality", "active_graph+margin", "convexity", "rank", "multipliers", "exact_identities"]

is_rejected(r) = any(b.status == :FAIL for b in r.blocks)
blockstatus(r, name) = (i = findfirst(b -> b.name == name, r.blocks); i === nothing ? "—" : String(r.blocks[i].status))

function find_candidates(dir)
    paths = String[]
    for (root, _, files) in walkdir(dir)
        for f in files
            f == "candidate.jl" && push!(paths, joinpath(root, f))
        end
    end
    return sort(paths)
end

is_negative_control(cand) = get(cand.meta, :expect, :structural_pass) == :reject

"""
    matches_filter(cand, arg)

CLI single-case filter. `arg` is the raw string typed after the script name.
`nothing` (no argument) matches everything. A bare integer ("4","6","8","16")
matches candidates with that `n`, excluding negative controls (so `16` means
the real A16 case, not the three deliberately-broken n=16 controls — use
"neg" for those). Anything else is a case-insensitive substring match against
the candidate name (e.g. "A16", "reinhardt", "neg", "convexity").
"""
function matches_filter(cand, arg::Union{Nothing,AbstractString})
    arg === nothing && return true
    lower = lowercase(arg)
    lower in ("all", "*") && return true
    lower in ("neg", "negative", "negatives") && return is_negative_control(cand)
    if all(isdigit, arg)
        return cand.n == parse(Int, arg) && !is_negative_control(cand)
    end
    return occursin(lower, lowercase(cand.name))
end

# Load-bearing for this certificate: the library, the pipeline, the tests, and
# every file under cases/ -- the candidates AND exact_coords.jl, which supplies
# their exact coordinates and was once left out of the hash list. Recursive, so
# a file moved into a subdirectory stays covered.
const SOURCE_DIRS = ("src", "pipeline", "test", "cases")

function source_hashes()
    files = String[]
    for d in SOURCE_DIRS
        top = joinpath(ROOT, d); isdir(top) || continue
        for (r, _, fs) in walkdir(top), f in fs
            endswith(f, ".jl") && push!(files, relpath(joinpath(r, f), ROOT))
        end
    end
    sort!(files)
    append!(files, ["Project.toml", "Manifest.toml"])
    return [(rel, bytes2hex(sha256(read(joinpath(ROOT, rel))))) for rel in files if isfile(joinpath(ROOT, rel))]
end

function git_state()
    try
        commit = strip(read(`git -C $ROOT rev-parse HEAD`, String))
        # This list said `tests` (no such directory) until 2026-09, so an
        # uncommitted edit to the test suite never marked the run dirty.
        # Explicit argument vector: inside backticks `$(SOURCE_DIRS...)` would
        # concatenate the names into one nonexistent path and report clean.
        cmd = Cmd(["git", "-C", ROOT, "status", "--porcelain", "--",
                   SOURCE_DIRS..., "Project.toml", "Manifest.toml"])
        dirty = !isempty(strip(read(cmd, String)))
        return commit, !dirty
    catch
        return "(unavailable)", false
    end
end

# ----- LaTeX table emission (Tables 1–4 of the paper) ----------------------

texesc(s) = replace(String(s), "_" => "\\_", "&" => "\\&", "#" => "\\#")

function emit_tables(rows, outdir)
    mkpath(outdir)
    pos = [r for r in rows if !r.negative]

    # Table 1 — benchmark summary
    open(joinpath(outdir, "table1_summary.tex"), "w") do io
        println(io, "% Auto-generated by pipeline/certify_literature.jl — do not edit.")
        println(io, "\\begin{tabular}{llrll}")
        println(io, "\\toprule")
        println(io, "Case & \$n\$ & Reference & DOI & Literature status \\\\ \\midrule")
        for r in pos
            @printf(io, "%s & %d & %s & %s & %s \\\\\n", texesc(r.name), r.n,
                    texesc(get(r.meta, :reference, "")), texesc(get(r.meta, :doi, "")),
                    startswith(get(r.meta, :status_literature, ""), "PROVEN") ? "THEOREM" :
                    startswith(get(r.meta, :status_literature, ""), "OPEN") ? "OPEN" : "—")
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end

    # Table 2 — certified properties per benchmark (full first-order certificate)
    open(joinpath(outdir, "table2_properties.tex"), "w") do io
        println(io, "% Auto-generated. Entries are per-block epistemic status.")
        println(io, "\\begin{tabular}{lccccccc}")
        println(io, "\\toprule")
        println(io, "Case & exist. & equilat. & active+marg. & convex. & rank & multipl. & exact id. \\\\ \\midrule")
        for r in pos
            @printf(io, "%s & %s & %s & %s & %s & %s & %s & %s \\\\\n", texesc(r.name),
                    r.blocks["existence"], r.blocks["equilaterality"], r.blocks["active_graph+margin"],
                    r.blocks["convexity"], r.blocks["rank"], r.blocks["multipliers"], r.blocks["exact_identities"])
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end

    # Table 3 — epistemic states legend + LICQ observation
    open(joinpath(outdir, "table3_epistemic.tex"), "w") do io
        println(io, "% Auto-generated. Epistemic levels and the LICQ observation.")
        println(io, "\\begin{tabular}{llr}")
        println(io, "\\toprule")
        println(io, "Case & multipliers (diagnostic) & LICQ defect \\(=\\#\\text{active}-(n-2)\\) \\\\ \\midrule")
        for r in pos
            @printf(io, "%s & %s & %d \\\\\n", texesc(r.name), r.blocks["multipliers"], r.licq_defect)
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end

    # Table 4 — bibliographic coverage
    open(joinpath(outdir, "table4_bibliography.tex"), "w") do io
        println(io, "% Auto-generated. Bibliographic coverage of the benchmark.")
        println(io, "\\begin{tabular}{llll}")
        println(io, "\\toprule")
        println(io, "Case & Problem & Result type & Reproducible data \\\\ \\midrule")
        for r in pos
            @printf(io, "%s & %s & %s & %s \\\\\n", texesc(r.name),
                    texesc(get(r.meta, :problem, "")),
                    startswith(get(r.meta, :status_literature, ""), "PROVEN") ? "theorem (global opt.)" :
                    startswith(get(r.meta, :status_literature, ""), "OPEN") ? "construction (open)" : "—",
                    texesc(get(r.meta, :constructor, "—")))
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end
end

function emit_certificate(rows, allok, elapsed_total, outpath)
    commit, clean = git_state()
    cert = Dict{String,Any}(
        "meta" => Dict{String,Any}(
            "utc" => Dates.format(now(UTC), "yyyy-mm-ddTHH:MM:SS") * "Z",
            "julia_version" => string(VERSION),
            "intervalarithmetic_version" => string(pkgversion(IntervalArithmetic)),
            "bigfloat_precision_bits" => 256,
            "git_commit" => commit,
            "git_source_clean" => clean,
            "total_seconds" => round(elapsed_total; digits = 3),
            "all_expectations_met" => allok,
        ),
        "source_sha256" => [Dict("file" => f, "sha256" => h) for (f, h) in source_hashes()],
        "benchmark" => [Dict{String,Any}(
            "name" => r.name, "n" => r.n,
            "reference" => get(r.meta, :reference, ""), "doi" => get(r.meta, :doi, ""),
            "literature_status" => get(r.meta, :status_literature, ""),
            "negative_control" => r.negative,
            "verdict" => r.verdict, "expectation_met" => r.met,
            "seconds" => round(r.seconds; digits = 3),
            "licq_defect" => r.licq_defect,
            "blocks" => Dict(k => r.blocks[k] for k in keys(r.blocks)),
        ) for r in rows],
    )
    open(outpath, "w") do io
        println(io, "# Reproducible validation certificate — auto-generated; do not edit.")
        println(io, "# Reconstruct: git checkout <git_commit>; julia --project=. pipeline/certify_literature.jl")
        TOML.print(io, cert; sorted = true)
    end
end

function print_usage()
    println("Usage: julia --project=. pipeline/certify_literature.jl [case]")
    println()
    println("  (no argument)      run all 9 cases (full benchmark) and write")
    println("                     results/validation_certificate.toml + results/tables/")
    println("  4 | 6 | 8 | 16 | 32 | 64   certify that n only (16 = A16, excludes the negative controls)")
    println("  A16 | reinhardt | ahmp2004 | ...   substring of the case name, case-insensitive")
    println("  neg                the 3 negative controls (these must be REJECTED)")
    println("  all                same as no argument")
    println()
    println("Available cases:")
    for path in find_candidates(joinpath(ROOT, "cases"))
        cand = include(path)
        tag = is_negative_control(cand) ? "  [negative control]" : ""
        println("  ", rpad(cand.name, 24), " n=", cand.n, tag)
    end
end

function main()
    filter_arg = isempty(ARGS) ? nothing : ARGS[1]
    if filter_arg !== nothing && lowercase(filter_arg) in ("-h", "--help", "help")
        print_usage()
        return true
    end
    full_run = filter_arg === nothing || lowercase(filter_arg) in ("all", "*")

    println("="^70)
    println("LITERATURE VALIDATION — general small-polygon first-order certifier")
    println("UTC ", Dates.format(now(UTC), "yyyy-mm-ddTHH:MM:SS"), "Z   Julia ", VERSION,
            "   IntervalArithmetic v", pkgversion(IntervalArithmetic))
    println("="^70)

    litdir = joinpath(ROOT, "cases")
    all_paths = find_candidates(litdir)
    all_cands = [include(path) for path in all_paths]
    selected = [cand for cand in all_cands if matches_filter(cand, filter_arg)]

    if isempty(selected)
        println("\nNo case matches \"", filter_arg, "\".\n")
        print_usage()
        return false
    end
    if !full_run
        println("Filter: \"", filter_arg, "\" → ", length(selected), " case(s): ",
                join((c.name for c in selected), ", "))
    end

    rows = NamedTuple[]
    all_ok = true
    t0 = time()

    for cand in selected
        radius = cand.root === nothing ? big"0" : big"1e-24"
        t = time(); r = certify(cand; radius = radius); dt = time() - t
        println(); show(r)

        rejected = is_rejected(r)
        negative = is_negative_control(cand)
        met = negative ? rejected : (structural_pass(r) && !rejected)
        all_ok &= met
        verdict = negative ? (rejected ? "REJECTED (as expected)" : "NOT rejected (UNEXPECTED)") :
                             (rejected ? "rejected (UNEXPECTED)" : "structural PASS")
        licq_defect = cand.n + length(cand.active) - (2*cand.n - 2)
        push!(rows, (name = cand.name, n = cand.n, meta = cand.meta, negative = negative,
                     verdict = verdict, met = met, seconds = dt, licq_defect = licq_defect,
                     blocks = Dict(bn => blockstatus(r, bn) for bn in BLOCK_ORDER)))
    end
    elapsed = time() - t0

    println("\n", "="^70, "\nSUMMARY\n", "="^70)
    @printf("%-26s %4s  %-14s  %-12s %s\n", "candidate", "n", "framework", "literature", "ok")
    println("-"^78)
    for r in rows
        fw = occursin("PASS", r.verdict) ? "CERTIFIED*" : occursin("REJECTED", r.verdict) ? "rejected" : "!!"
        lit = r.negative ? "neg-control" : startswith(get(r.meta,:status_literature,""), "PROVEN") ? "THEOREM" :
              startswith(get(r.meta,:status_literature,""), "OPEN") ? "OPEN" : "?"
        @printf("%-26s %4d  %-14s  %-12s %s\n", r.name, r.n, fw, lit, r.met ? "✓" : "✗")
    end
    println("-"^78)
    println("* CERTIFIED* now denotes the FULL local strict first-order certificate, general in n:")
    println("  existence [IVT], strict convexity (Lemma L2), active graph + directed margin,")
    println("  rank=2n-2 ⇒ I_eq=R_eq, CERTIFIED positive KKT multipliers (interval Krawczyk, R1),")
    println("  and PROVEN exact side/diameter identities (exact Q(c,s) algebra, R2). Multipliers and")
    println("  exact identities are no longer A16-exclusive. THEOREM = global optimum PROVEN IN THE")
    println("  LITERATURE, NOT re-proved here (the framework certifies only local first-order data).")
    println("  OPEN = A16 best known, not proven optimal. Scope/limits: docs/guide/scope-and-limitations.md.")

    # CHIQUI_NO_RECORD=1: a full run that checks everything but writes no
    # record (make check). A quick check should not rewrite results/.
    record = full_run && get(ENV, "CHIQUI_NO_RECORD", "") != "1"
    if record
        emit_certificate(rows, all_ok, elapsed, joinpath(ROOT, "results", "validation_certificate.toml"))
        emit_tables(rows, joinpath(ROOT, "results", "tables"))
        println("\nwrote results/validation_certificate.toml and results/tables/table{1,2,3,4}_*.tex")
    elseif full_run
        println("\n(CHIQUI_NO_RECORD=1 — every case was run, results/ was left untouched)")
    else
        println("\n(filtered run — results/validation_certificate.toml was left untouched;")
        println(" run with no argument to regenerate the full certificate)")
    end
    println("="^70)
    println(all_ok ? "ALL EXPECTATIONS MET" : "SOME EXPECTATION NOT MET")
    println("="^70)
    return all_ok
end

ok = main()
(abspath(PROGRAM_FILE) == @__FILE__) && exit(ok ? 0 : 1)
