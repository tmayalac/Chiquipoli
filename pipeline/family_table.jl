# The article's table of the family A_n, n = 16, ..., 1024, written from the
# family certificates (results/family/A<n>.toml) and nothing else.
#
#     julia --project=. pipeline/family_table.jl      -> results/tables/table5_family.tex
#
# Every printed lower bound is the certified bound ROUNDED DOWN to four
# significant digits, so the printed number is itself a certified lower bound;
# the perimeter is printed to ten decimals from an enclosure of width < 1e-27.
# `make paper-check` requires the article to contain exactly these rows.
module FamilyTable
using TOML, Printf

const ROOT = normpath(joinpath(@__DIR__, ".."))
_family(name) = parse.(Int, split(something(match(Regex("^const $name = \\((.*)\\)", "m"),
    read(joinpath(ROOT, "cases", "exact_coords.jl"), String)).captures[1]), ','))
const FAMILY_N = _family("FAMILY_N")
const FAMILY_LEAN_N = _family("FAMILY_LEAN_N")
const FAMILY_TRIG_N = _family("FAMILY_TRIG_N")

"`x` rounded DOWN to `d` significant digits, as a LaTeX number."
function floor_sig(x::BigFloat; d = 4)
    x > 0 || error("a certified lower bound must be positive, got $x")
    e = floor(Int, log10(x))
    m = floor(x / big(10.0)^(e - d + 1)) / big(10)^(d - 1)      # d-digit mantissa, rounded down
    mant = @sprintf("%.*f", d - 1, Float64(m))
    e == 0 ? mant : "$(mant)\\times10^{$e}"
end

function detail_number(g, re)
    m = match(re, g["detail"])
    m === nothing && error("cannot read $(re) from gate $(g["id"]): $(g["detail"])")
    parse(BigFloat, m.captures[1])
end

function row(n)
    path = joinpath(ROOT, "results", "family", "A$n.toml")
    isfile(path) || error("missing $path: run julia --project=. pipeline/certify_family.jl $n")
    rec = TOML.parsefile(path)
    get(rec, "certified", false) || error("A$n is not CERTIFIED in $path")
    g = Dict(x["id"] => x for x in rec["gate"])
    all(x -> x["passed"], rec["gate"]) && length(rec["gate"]) == 10 || error("A$n: not all 10 gates passed")
    perim = parse(BigFloat, g["side_length"]["perimeter"])
    conv = detail_number(g["convexity"], r"min inf = ([0-9.eE+-]+)")
    marg = detail_number(g["inactive_margin"], r"margin≥([0-9.eE+-]+)")
    lam = detail_number(g["multipliers"], r"≥ ([0-9.eE+-]+) > 0")
    lean = n in FAMILY_TRIG_N ? (n in FAMILY_LEAN_N ? "both" : "general") : "---"
    @sprintf("%d & \\(%.10f\\) & \\(%s\\) & \\(%s\\) & \\(%s\\) & %s\\\\", n, Float64(perim),
             floor_sig(conv), floor_sig(marg), floor_sig(lam), lean)
end

"The table, as the article must print it, from the family certificates."
family_table_tex() = join([
    "% Auto-generated by pipeline/family_table.jl from results/family/A<n>.toml — do not edit.",
    "\\begin{tabular}{@{}rlllll@{}}",
    "\\toprule",
    "\\(n\\) & \\(n\\ell\\) & \\(\\min\\det\\ \\geq\\) & \\(\\delta_{\\mathrm{inact}}\\ \\geq\\) & \\(\\min\\lambda_{ij}\\ \\geq\\) & Lean\\\\",
    "\\midrule",
    [row(n) for n in FAMILY_N]...,
    "\\bottomrule",
    "\\end{tabular}", ""], "\n")

end # module FamilyTable

if abspath(PROGRAM_FILE) == @__FILE__
    tex = FamilyTable.family_table_tex()
    out = joinpath(FamilyTable.ROOT, "results", "tables", "table5_family.tex")
    write(out, tex)
    println(tex)
    println("wrote ", relpath(out, FamilyTable.ROOT))
end
